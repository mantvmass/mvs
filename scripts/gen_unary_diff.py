#!/usr/bin/env python3
"""Generate the unary-operator axis: tests/diff/unary_<type>.{mvs,c}

ops_diff tests ~a (bitwise NOT) and 0-a (subtraction) but not:
  - unary -x (ND_UNARY with TK_MINUS, distinct codegen from binary sub)
  - !x (logical NOT, completely untested)
  - -x on unsigned types (modular wrap)

This axis fills those gaps with edge values for each integer type.

Run from the repo root: python3 scripts/gen_unary_diff.py
"""
import os

TYPES = [
    # (mvs_name, c_type, signed, bits)
    ("i8",    "int8_t",    True,  8),
    ("i16",   "int16_t",   True,  16),
    ("i32",   "int32_t",   True,  32),
    ("i64",   "int64_t",   True,  64),
    ("isize", "intptr_t",  True,  64),
    ("u8",    "uint8_t",   False, 8),
    ("u16",   "uint16_t",  False, 16),
    ("u32",   "uint32_t",  False, 32),
    ("u64",   "uint64_t",  False, 64),
    ("usize", "uintptr_t", False, 64),
]


def values(signed, bits):
    """Edge values for unary operator testing."""
    if signed:
        lo = -(1 << (bits - 1))
        hi = (1 << (bits - 1)) - 1
        return [0, 1, -1, lo, hi, lo + 1, hi - 1, -7, 42]
    else:
        hi = (1 << bits) - 1
        return [0, 1, hi, hi - 1, 128 % (1 << bits) or 1, 7, 42]


def cint(v):
    if v > 0x7FFFFFFFFFFFFFFF:
        return '%dULL' % v
    if v < -0x7FFFFFFFFFFFFFFF:
        return '(-9223372036854775807LL - 1)'
    return '%dLL' % v


def gen(name, ctype, signed, bits):
    fmt = "%lld" if signed else "%llu"
    cast = "(long long)" if signed else "(unsigned long long)"
    ext = "(uint64_t)(int64_t)" if signed else "(uint64_t)"
    m = [
        '// GENERATED by scripts/gen_unary_diff.py: unary ops on %s' % name,
        '// C file is the reference; difftest.sh requires identical output.',
        'use std::io;',
        '',
        'func main() -> i8 {',
    ]
    c = [
        '/* GENERATED by scripts/gen_unary_diff.py: reference for unary_%s.mvs */' % name,
        '#include <stdio.h>',
        '#include <stdint.h>',
        '',
        'int main(void) {',
    ]
    n = 0
    for v in values(signed, bits):
        m.append('    {')
        c.append('    {')
        m.append('        let a: %s = %s;' % (name, v))
        c.append('        %s a = (%s)%s;' % (ctype, ctype, cint(v)))

        # Unary minus: -a
        # MVS: neg rax (64-bit), result assigned to target type (truncates)
        # C model: negate in 64-bit unsigned (no UB), truncate to target type
        m.append('        let r_neg: %s = -a; io.out("{}", r_neg);' % name)
        c.append('        {')
        c.append('            uint64_t a64 = %sa;' % ext)
        c.append('            uint64_t r64 = (uint64_t)(-(int64_t)a64);')
        c.append('            %s result = (%s)r64;' % (ctype, ctype))
        c.append('            printf("%s\\n", %s result);' % (fmt, cast))
        c.append('        }')
        n += 1

        # Bitwise NOT: ~a
        # MVS: not rax, then truncate to type width (movsx/movzx)
        # C model: ~a64, truncate to target type
        m.append('        let r_not: %s = ~a; io.out("{}", r_not);' % name)
        c.append('        {')
        c.append('            uint64_t a64 = %sa;' % ext)
        c.append('            uint64_t r64 = ~a64;')
        c.append('            %s result = (%s)r64;' % (ctype, ctype))
        c.append('            printf("%s\\n", %s result);' % (fmt, cast))
        c.append('        }')
        n += 1

        # Logical NOT: !a
        # MVS: cmp rax, 0; sete al; movzx rax, al -> produces 0 or 1
        # C: !a -> 0 or 1
        m.append('        let r_lnot: bool = !a; io.out("{}", r_lnot as i32);')
        c.append('        printf("%d\\n", !a ? 1 : 0);')
        n += 1

        m.append('    }')
        c.append('    }')
    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


def main():
    out = os.path.join('tests', 'diff')
    os.makedirs(out, exist_ok=True)
    total = 0
    for name, ctype, signed, bits in TYPES:
        mvs, ref, n = gen(name, ctype, signed, bits)
        with open(os.path.join(out, 'unary_%s.mvs' % name), 'w', newline='\n') as f:
            f.write(mvs)
        with open(os.path.join(out, 'unary_%s.c' % name), 'w', newline='\n') as f:
            f.write(ref)
        total += n
        print('  wrote unary_%s  (%d checks)' % (name, n))
    print('total: %d unary-operator checks' % total)


if __name__ == '__main__':
    main()
