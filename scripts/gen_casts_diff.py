#!/usr/bin/env python3
"""Generate the cast axis of the audit: tests/diff/casts_<type>.{mvs,c}

Every numeric type cast to every other numeric type, with C as the oracle.
The pair lands in tests/diff/, so scripts/difftest.sh (and therefore audit.sh
and CI) picks it up with no extra plumbing: a mismatch means MVS generated
wrong code for a cast, not that a golden drifted.

Run from the repo root: python3 scripts/gen_casts_diff.py
"""
import os

INT_TYPES = [
    # mvs_name, c_type, signed, bits
    ("i8",    "int8_t",    True,  8),
    ("i16",   "int16_t",   True,  16),
    ("i32",   "int32_t",   True,  32),
    ("i64",   "int64_t",   True,  64),
    ("isize", "intptr_t",  True,  64),
    ("u8",    "uint8_t",   False, 8),
    ("u16",   "uint16_t",  False, 16),
    ("u32",   "uint32_t",  False, 32),
    ("u64",   "uint64_t",  False, 64),
    ("usize", "uintptr_t", False, 64),
]

FLOAT_TYPES = [
    # mvs_name, c_type, suffix, bits
    ("f32", "float",  "f", 32),
    ("f64", "double", "",  64),
]

ALL_TYPES = INT_TYPES + [(n, c, None, b) for n, c, _, b in FLOAT_TYPES]

def type_is_signed(entry):
    return entry[2] is True

def type_is_unsigned(entry):
    return entry[2] is False

def type_is_float(entry):
    return entry[2] is None

def type_bits(entry):
    return entry[3]

def type_range(entry):
    """(min_val, max_val) as Python ints for integer types."""
    signed, bits = entry[2], entry[3]
    if signed:
        return (-(1 << (bits - 1)), (1 << (bits - 1)) - 1)
    return (0, (1 << bits) - 1)

def cint(v):
    """C literal for 64-bit integer, matching gen_ops_diff.py."""
    if v > 0x7fffffffffffffff:
        return '%dULL' % v
    if v < -0x7fffffffffffffff:
        return '(-9223372036854775807LL - 1)'
    return '%dLL' % v

def cfloat(v, suffix):
    return '%r%s' % (v, suffix)

def c_printf(target, expr):
    """Full printf statement for printing a value of the target type in C."""
    name = target[0]
    if name in ("f32", "f64"):
        return 'printf("%%f\\n", (double)%s);' % expr
    if type_is_signed(target):
        return 'printf("%%lld\\n", (long long)%s);' % expr
    return 'printf("%%llu\\n", (unsigned long long)%s);' % expr

def int_test_values(signed, bits):
    """Representative values for an integer source type."""
    if signed:
        hi = (1 << (bits - 1)) - 1
        lo = -(1 << (bits - 1))
        vals = [0, 1, -1, hi, lo]
        mid = hi // 2 + 1
        if mid not in vals:
            vals.append(mid)
        return vals
    hi = (1 << bits) - 1
    vals = [0, 1, hi]
    mid = hi // 2 + 1
    if mid not in vals:
        vals.append(mid)
    return vals

FLOAT_TEST_VALUES = [0.0, 1.5, -1.5, 42.75, 100.0, -100.0, 0.125]

def float_values_safe_for_int(target):
    """Float values that are safe to cast to the given integer target (no UB)."""
    lo, hi = type_range(target)
    safe = []
    for v in FLOAT_TEST_VALUES:
        iv = int(v)
        if lo <= iv <= hi:
            safe.append(v)
    if 0.0 not in safe:
        safe.append(0.0)
    return safe


def gen_int_source(src):
    """Generate casts_<int_type>.mvs and .c for one integer source type."""
    sname, sctype, ssigned, sbits = src
    targets = [t for t in ALL_TYPES if t[0] != sname]
    # isize/usize are aliases of i64/u64 at 64 bits; skip casting between them
    skip_pairs = {("i64", "isize"), ("isize", "i64"), ("u64", "usize"), ("usize", "u64")}
    targets = [t for t in targets if (sname, t[0]) not in skip_pairs]

    m = ['// GENERATED by scripts/gen_casts_diff.py: every cast from ' + sname,
         '// The C file next to it is the reference; difftest.sh requires identical output.',
         'use std::io;', '', 'func main() -> i8 {']
    c = ['/* GENERATED by scripts/gen_casts_diff.py: reference for casts_%s.mvs */' % sname,
         '#include <stdio.h>', '#include <stdint.h>', '', 'int main(void) {']
    n = 0
    vals = int_test_values(ssigned, sbits)

    for v in vals:
        m.append('    {')
        c.append('    {')
        m.append('        let a: %s = %s;' % (sname, str(v)))
        c.append('        %s a = (%s)%s;' % (sctype, sctype, cint(v)))
        for tgt in targets:
            tname, tctype = tgt[0], tgt[1]
            m.append('        let r_%s: %s = a as %s; io.out("{}", r_%s);' % (tname, tname, tname, tname))
            c.append('        { %s r = (%s)a; %s }' % (tctype, tctype, c_printf(tgt, 'r')))
            n += 1
        m.append('    }')
        c.append('    }')

    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


def gen_float_source(src):
    """Generate casts_<float_type>.mvs and .c for one float source type."""
    sname, sctype, ssuffix, sbits = src
    # float-to-float target
    other_float = [t for t in FLOAT_TYPES if t[0] != sname]
    # all integer targets
    int_targets = list(INT_TYPES)
    # skip isize (same as i64) and usize (same as u64) to keep output shorter
    int_targets = [t for t in int_targets if t[0] not in ("isize", "usize")]

    m = ['// GENERATED by scripts/gen_casts_diff.py: every cast from ' + sname,
         '// The C file next to it is the reference; difftest.sh requires identical output.',
         'use std::io;', '', 'func main() -> i8 {']
    c = ['/* GENERATED by scripts/gen_casts_diff.py: reference for casts_%s.mvs */' % sname,
         '#include <stdio.h>', '#include <stdint.h>', '', 'int main(void) {']
    n = 0
    vid = 0

    # float to float: use all values (always safe)
    for v in FLOAT_TEST_VALUES:
        vid += 1
        m.append('    {')
        c.append('    {')
        m.append('        let a: %s = %r;' % (sname, v))
        c.append('        %s a = %s;' % (sctype, cfloat(v, ssuffix)))
        for oft in other_float:
            tname, tctype = oft[0], oft[1]
            m.append('        let r_%s: %s = a as %s; io.out("{}", r_%s);' % (tname, tname, tname, tname))
            c.append('        { %s r = (%s)a; %s }' % (tctype, tctype, c_printf(oft, 'r')))
            n += 1
        m.append('    }')
        c.append('    }')

    # float to each integer target: per-target safe values
    for tgt in int_targets:
        tname, tctype = tgt[0], tgt[1]
        safe_vals = float_values_safe_for_int(tgt)
        for v in safe_vals:
            vid += 1
            m.append('    {')
            c.append('    {')
            m.append('        let a: %s = %r;' % (sname, v))
            c.append('        %s a = %s;' % (sctype, cfloat(v, ssuffix)))
            m.append('        let r_%s: %s = a as %s; io.out("{}", r_%s);' % (tname, tname, tname, tname))
            c.append('        { %s r = (%s)a; %s }' % (tctype, tctype, c_printf(tgt, 'r')))
            n += 1
            m.append('    }')
            c.append('    }')

    # also test int-to-this-float (round trip: int -> float -> print)
    # using small values that are exact in both f32 and f64
    round_trip_vals = [0, 1, -1, 42, -100, 127, -128, 255, 1000, -1000]
    m.append('    // int to %s round trip' % sname)
    c.append('    /* int to %s round trip */' % sname)
    for iv in round_trip_vals:
        vid += 1
        m.append('    {')
        c.append('    {')
        m.append('        let a: i64 = %d;' % iv)
        c.append('        int64_t a = %s;' % cint(iv))
        m.append('        let r: %s = a as %s; io.out("{}", r);' % (sname, sname))
        c.append('        { %s r = (%s)a; %s }' % (sctype, sctype, c_printf((sname, sctype, None, sbits), 'r')))
        n += 1
        m.append('    }')
        c.append('    }')

    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


total = 0
os.makedirs('tests/diff', exist_ok=True)

for src in INT_TYPES:
    mvs, cref, n = gen_int_source(src)
    open('tests/diff/casts_%s.mvs' % src[0], 'w', newline='\n').write(mvs)
    open('tests/diff/casts_%s.c' % src[0], 'w', newline='\n').write(cref)
    total += n
    print('casts_%s: %d checks' % (src[0], n))

for src in FLOAT_TYPES:
    mvs, cref, n = gen_float_source(src)
    open('tests/diff/casts_%s.mvs' % src[0], 'w', newline='\n').write(mvs)
    open('tests/diff/casts_%s.c' % src[0], 'w', newline='\n').write(cref)
    total += n
    print('casts_%s: %d checks' % (src[0], n))

print("total %d cast checks across %d types" % (total, len(INT_TYPES) + len(FLOAT_TYPES)))
