#!/usr/bin/env python3
"""Generate the mixed-type binary-op axis: tests/diff/mixed_<tag>.{mvs,c}

Every binary operator across selected cross-type pairs with boundary
values. The C reference models MVS register-level behavior (64-bit
arithmetic on sign/zero-extended operands, no type-width truncation).
Comparisons use native C promotions which should match the backend
fixes for mixed-sign setcc and normalize.

Run from the repo root: python3 scripts/gen_mixed_diff.py
"""
import os

PAIRS = [
    ("i8",  "int8_t",   "u8",  "uint8_t",   "i8_u8"),
    ("i16", "int16_t",  "u16", "uint16_t",   "i16_u16"),
    ("i32", "int32_t",  "u32", "uint32_t",   "i32_u32"),
    ("i64", "int64_t",  "u64", "uint64_t",   "i64_u64"),
    ("i8",  "int8_t",   "u32", "uint32_t",   "i8_u32"),
    ("i16", "int16_t",  "u64", "uint64_t",   "i16_u64"),
    ("u8",  "uint8_t",  "i32", "int32_t",    "u8_i32"),
    ("u16", "uint16_t", "i64", "int64_t",    "u16_i64"),
    ("i32", "int32_t",  "f64", "double",     "i32_f64"),
    ("u64", "uint64_t", "f64", "double",     "u64_f64"),
]


def type_rank(t):
    return {"i8":1,"u8":1,"i16":2,"u16":2,"i32":4,"u32":4,
            "i64":8,"u64":8,"f32":4,"f64":8}[t]


def is_float(t):
    return t in ("f32", "f64")


def is_signed(t):
    return t[0] in ('i', 'f')


def mvs_result_signed(ml, mr):
    """Whether MVS infers a signed result type (for io.out format)."""
    if is_float(ml) or is_float(mr):
        return True
    if type_rank(mr) > type_rank(ml):
        return is_signed(mr)
    return is_signed(ml)


def div_is_unsigned(ml):
    """MVS division uses left operand signedness."""
    return not is_signed(ml)


def cint(v):
    if v > 0x7fffffffffffffff:
        return '%dULL' % v
    if v < -0x7fffffffffffffff:
        return '(-9223372036854775807LL - 1)'
    return '%dLL' % v


def test_values(mvs_l, mvs_r):
    def bounds(name):
        tbl = {
            "i8": (-128, 127, True, 8),
            "i16": (-32768, 32767, True, 16),
            "i32": (-2147483648, 2147483647, True, 32),
            "i64": (-9223372036854775808, 9223372036854775807, True, 64),
            "u8": (0, 255, False, 8),
            "u16": (0, 65535, False, 16),
            "u32": (0, 4294967295, False, 32),
            "u64": (0, 18446744073709551615, False, 64),
            "f64": (None, None, True, 64),
        }
        return tbl.get(name, (0, 0, True, 64))

    lo_l, hi_l, signed_l, bits_l = bounds(mvs_l)
    lo_r, hi_r, signed_r, bits_r = bounds(mvs_r)

    if is_float(mvs_l) or is_float(mvs_r):
        return [(0, 1.0), (1, 2.5), (-1, 3.0), (42, 0.5)]

    pairs = [(0, 0), (1, 1)]
    if signed_l:
        pairs.append((-1, hi_r))
        pairs.append((lo_l, 1))
        if not signed_r:
            pairs.append((-1, 1))
    if signed_r:
        pairs.append((hi_l if hi_l is not None else 127, -1))
    if not signed_l and signed_r:
        pairs.append((hi_l, -1))
    if signed_l and not signed_r and bits_l == bits_r:
        pairs.append((-1, (1 << bits_r) - 1))
    if not signed_l and signed_r and bits_l == bits_r:
        pairs.append(((1 << bits_l) - 1, -1))

    seen = set()
    result = []
    for p in pairs:
        if p not in seen:
            seen.add(p)
            result.append(p)
    return result


ARITH_OPS = [("+",), ("-",), ("*",)]
CMP_OPS = [("==",), ("!=",), ("<",), (">",), ("<=",), (">=",)]


def gen_pair(mvs_l, c_l, mvs_r, c_r, tag):
    is_flt = is_float(mvs_l) or is_float(mvs_r)
    res_signed = mvs_result_signed(mvs_l, mvs_r)
    left_unsigned_div = div_is_unsigned(mvs_l)

    if is_flt:
        fmt_arith = '%f'
        cast_arith = '(double)'
    elif res_signed:
        fmt_arith = '%lld'
        cast_arith = '(long long)(int64_t)'
    else:
        fmt_arith = '%llu'
        cast_arith = '(unsigned long long)'

    m = [
        '// GENERATED by scripts/gen_mixed_diff.py: mixed-type ops %s vs %s' % (mvs_l, mvs_r),
        'import { io } from "std";',
        '',
        'func main() -> i8 {',
    ]
    c = [
        '/* GENERATED by scripts/gen_mixed_diff.py: reference for mixed_%s.mvs */' % tag,
        '#include <stdio.h>',
        '#include <stdint.h>',
        '',
        'int main(void) {',
    ]
    n = 0

    for (a, b) in test_values(mvs_l, mvs_r):
        m.append('    {')
        c.append('    {')

        if is_float(mvs_l):
            m.append('        let a: %s = %r;' % (mvs_l, a))
            c.append('        %s a = %r;' % (c_l, a))
        else:
            m.append('        let a: %s = %s;' % (mvs_l, str(a)))
            c.append('        %s a = (%s)%s;' % (c_l, c_l, cint(a)))

        if is_float(mvs_r):
            m.append('        let b: %s = %r;' % (mvs_r, b))
            c.append('        %s b = %r;' % (c_r, b))
        else:
            m.append('        let b: %s = %s;' % (mvs_r, str(b)))
            c.append('        %s b = (%s)%s;' % (c_r, c_r, cint(b)))

        if not is_flt:
            c.append('        int64_t la = (int64_t)a, lb = (int64_t)b;')

        for (op,) in ARITH_OPS:
            m.append('        io.out("{}", a %s b);' % op)
            if is_flt:
                c.append('        printf("%s\\n", %s(a %s b));' % (fmt_arith, cast_arith, op))
            else:
                c.append('        printf("%s\\n", %s((uint64_t)la %s (uint64_t)lb));' % (fmt_arith, cast_arith, op))
            n += 1

        # division (skip divisor==0)
        skip_div = False
        if isinstance(b, (int,)) and b == 0:
            skip_div = True
        if isinstance(b, float) and b == 0.0:
            skip_div = True
        if not skip_div:
            m.append('        io.out("{}", a / b);')
            if is_flt:
                c.append('        printf("%s\\n", %s(a / b));' % (fmt_arith, cast_arith))
            elif left_unsigned_div:
                c.append('        printf("%s\\n", %s((uint64_t)la / (uint64_t)lb));' % (fmt_arith, cast_arith))
            else:
                c.append('        printf("%s\\n", %s(la / lb));' % (fmt_arith, cast_arith))
            n += 1

        # comparisons: use native C types (promotions match MVS after backend fixes)
        for (op,) in CMP_OPS:
            m.append('        io.out("{}", (a %s b) as i32);' % op)
            c.append('        printf("%%d\\n", (int)(a %s b));' % op)
            n += 1

        m.append('    }')
        c.append('    }')

    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


def main():
    out = os.path.join('tests', 'diff')
    os.makedirs(out, exist_ok=True)
    total = 0

    for mvs_l, c_l, mvs_r, c_r, tag in PAIRS:
        mvs, ref, n = gen_pair(mvs_l, c_l, mvs_r, c_r, tag)
        with open(os.path.join(out, 'mixed_%s.mvs' % tag), 'w', newline='\n') as f:
            f.write(mvs)
        with open(os.path.join(out, 'mixed_%s.c' % tag), 'w', newline='\n') as f:
            f.write(ref)
        total += n
        print('  wrote mixed_%s  (%d checks)' % (tag, n))

    print('total: %d mixed-type checks' % total)


if __name__ == '__main__':
    main()
