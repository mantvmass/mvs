#!/usr/bin/env python3
"""Generate the power-operator axis: tests/diff/pow_<tag>.{mvs,c}

Every integer type through the ** operator with boundary and edge-case
exponents.  The C reference models MVS backend behavior: the loop uses a
signed comparison on the exponent (jle / b.le), so negative exponents
return 1, and imul / mul produces the same low bits as unsigned multiply.

Float ** tests are included for f64 (float base with integer exponent).

Run from the repo root: python3 scripts/gen_pow_diff.py
"""
import os

INT_TYPES = [
    # (mvs_name, c_type, signed, bits)
    ("i8",    "int8_t",    True,  8),
    ("i16",   "int16_t",   True,  16),
    ("i32",   "int32_t",   True,  32),
    ("i64",   "int64_t",   True,  64),
    ("u8",    "uint8_t",   False, 8),
    ("u16",   "uint16_t",  False, 16),
    ("u32",   "uint32_t",  False, 32),
    ("u64",   "uint64_t",  False, 64),
]

# (base, exponent) pairs that exercise interesting paths
def int_pairs(signed, bits):
    """Test pairs for same-type integer power."""
    ps = [
        (2, 0),    # anything ** 0 = 1
        (2, 1),    # anything ** 1 = itself
        (2, 10),   # basic power
        (1, 100),  # 1 ** n = 1
        (0, 0),    # 0 ** 0 = 1 (by convention in the loop)
        (0, 5),    # 0 ** n = 0
        (3, 3),    # 3 ** 3 = 27
        (5, 2),    # 5 ** 2 = 25
        (7, 4),    # 7 ** 4 = 2401
    ]
    if signed:
        ps += [
            (-1, 3),   # (-1) ** odd = -1
            (-1, 4),   # (-1) ** even = 1
            (-2, 3),   # (-2) ** 3 = -8
            (-2, 0),   # (-2) ** 0 = 1
            (-3, 2),   # (-3) ** 2 = 9
            (2, -1),   # negative exp: 1/2 -> 0
            (-1, -1),  # negative exp: 1/(-1) -> -1
            (-1, -2),  # negative exp: 1/1 -> 1
            (3, -2),   # negative exp: 1/9 -> 0
            (1, -5),   # negative exp: 1/1 -> 1
        ]
    # larger exponent that overflows for base > 1 (tests wrap behavior)
    if bits >= 16:
        ps.append((2, 15))  # 32768, overflows i16
    if bits >= 32:
        ps.append((2, 31))  # 2147483648, overflows i32
    return ps


def cint(v):
    if v > 0x7FFFFFFFFFFFFFFF:
        return '%dULL' % v
    if v < -0x7FFFFFFFFFFFFFFF:
        return '(-9223372036854775807LL - 1)'
    return '%dLL' % v


def gen_int(name, ctype, signed, bits):
    """Generate same-type integer power tests.

    The MVS backend computes power with 64-bit imul (same low bits as unsigned
    multiply), then stores to the target type (truncating), then io.out loads
    with sign/zero extension.  The C reference models this: compute in uint64_t
    (no signed overflow UB), truncate to the target type, extend for printing.
    """
    fmt = "%lld" if signed else "%llu"
    cast = "(long long)" if signed else "(unsigned long long)"
    # how to sign/zero extend the base into 64-bit in C
    ext = "(uint64_t)(int64_t)" if signed else "(uint64_t)"
    m = [
        '// GENERATED by scripts/gen_pow_diff.py: ** operator on %s' % name,
        '// C file is the reference; difftest.sh requires identical output.',
        'import { io } from "std";',
        '',
        'func main() -> i8 {',
    ]
    c = [
        '/* GENERATED by scripts/gen_pow_diff.py: reference for pow_%s.mvs */' % name,
        '#include <stdio.h>',
        '#include <stdint.h>',
        '',
        'int main(void) {',
    ]
    n = 0
    for (base, exp) in int_pairs(signed, bits):
        m.append('    {')
        c.append('    {')
        m.append('        let a: %s = %s;' % (name, base))
        m.append('        let e: %s = %s;' % (name, exp))
        c.append('        %s a = (%s)%s;' % (ctype, ctype, cint(base)))
        c.append('        %s e = (%s)%s;' % (ctype, ctype, cint(exp)))
        m.append('        let r: %s = a ** e; io.out("{}", r);' % name)
        # C: model the backend (abs exponent loop, 64-bit 1/result if negative, then truncate)
        c.append('        {')
        c.append('            uint64_t base64 = %sa;' % ext)
        c.append('            int64_t orig = (int64_t)e, ex = orig < 0 ? -orig : orig;')
        c.append('            uint64_t r64 = 1;')
        c.append('            while (ex > 0) { r64 *= base64; ex--; }')
        if signed:
            c.append('            if (orig < 0) r64 = (uint64_t)((int64_t)1 / (int64_t)r64);')
        else:
            c.append('            if (orig < 0) r64 = (uint64_t)1 / r64;')
        c.append('            %s result = (%s)r64;' % (ctype, ctype))
        c.append('            printf("%s\\n", %s result);' % (fmt, cast))
        c.append('        }')
        n += 1
        m.append('    }')
        c.append('    }')
    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


FLOAT_POW_CASES = [
    (2.0, 0),
    (2.0, 1),
    (2.0, 10),
    (0.5, 3),
    (1.0, 100),
    (0.0, 5),
    (3.14, 2),
    (-2.0, 3),
    (-2.0, 4),
    (-1.0, 7),
    (10.0, 6),
    (0.1, 3),
    (2.0, -3),    # negative exp: 1/8 = 0.125
    (10.0, -1),   # negative exp: 1/10 = 0.1
    (0.5, -2),    # negative exp: 1/0.25 = 4.0
    (-2.0, -3),   # negative exp: 1/(-8) = -0.125
    (-1.0, -5),   # negative exp: 1/(-1) = -1.0
    (5.0, -1),    # negative exp: 1/5 = 0.2
]


def gen_float():
    """Generate f64 ** integer power tests."""
    m = [
        '// GENERATED by scripts/gen_pow_diff.py: ** operator on f64',
        '// C file is the reference; difftest.sh requires identical output.',
        'import { io } from "std";',
        '',
        'func main() -> i8 {',
    ]
    c = [
        '/* GENERATED by scripts/gen_pow_diff.py: reference for pow_f64.mvs */',
        '#include <stdio.h>',
        '',
        'int main(void) {',
    ]
    n = 0
    for (base, exp) in FLOAT_POW_CASES:
        m.append('    {')
        c.append('    {')
        m.append('        let a: f64 = %r;' % base)
        m.append('        let e: i32 = %d;' % exp)
        c.append('        double a = %r;' % base)
        c.append('        int e = %d;' % exp)
        m.append('        let r: f64 = a ** e; io.out("{}", r);')
        # C: model the backend (abs exponent loop, invert if negative)
        c.append('        {')
        c.append('            double base = a;')
        c.append('            int orig = e, ex = e < 0 ? -e : e;')
        c.append('            double result = 1.0;')
        c.append('            while (ex > 0) { result *= base; ex--; }')
        c.append('            if (orig < 0) result = 1.0 / result;')
        c.append('            printf("%f\\n", result);')
        c.append('        }')
        n += 1
        m.append('    }')
        c.append('    }')
    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


CROSS_PAIRS = [
    # (base_mvs, base_c, exp_mvs, exp_c, tag)
    ("i32", "int32_t", "u8",  "uint8_t",  "i32_u8"),
    ("u64", "uint64_t", "i32", "int32_t",  "u64_i32"),
    ("i8",  "int8_t",  "i32", "int32_t",   "i8_i32"),
]

CROSS_VALUES = [
    (2, 10),
    (3, 3),
    (0, 0),
    (1, 50),
    (-1, 3),
    (-2, 4),
    (5, 0),
    (7, 5),
    (-1, -1),
    (2, -3),
    (1, -10),
]


def type_rank(t):
    return {"i8": 1, "u8": 1, "i16": 2, "u16": 2,
            "i32": 4, "u32": 4, "i64": 8, "u64": 8}[t]


def is_signed(t):
    return t[0] == 'i'


def mvs_result_signed(ml, mr):
    if type_rank(mr) > type_rank(ml):
        return is_signed(mr)
    return is_signed(ml)


def gen_cross(base_mvs, base_c, exp_mvs, exp_c, tag):
    """Generate cross-type power tests."""
    res_signed = mvs_result_signed(base_mvs, exp_mvs)
    fmt = "%lld" if res_signed else "%llu"
    cast = "(long long)" if res_signed else "(unsigned long long)"
    base_signed = is_signed(base_mvs)

    m = [
        '// GENERATED by scripts/gen_pow_diff.py: ** cross-type %s ** %s' % (base_mvs, exp_mvs),
        'import { io } from "std";',
        '',
        'func main() -> i8 {',
    ]
    c = [
        '/* GENERATED by scripts/gen_pow_diff.py: reference for pow_%s.mvs */' % tag,
        '#include <stdio.h>',
        '#include <stdint.h>',
        '',
        'int main(void) {',
    ]
    n = 0
    for (base, exp) in CROSS_VALUES:
        if not base_signed and base < 0:
            continue
        m.append('    {')
        c.append('    {')
        m.append('        let a: %s = %s;' % (base_mvs, base))
        m.append('        let e: %s = %s;' % (exp_mvs, exp))
        c.append('        %s a = (%s)%s;' % (base_c, base_c, cint(base)))
        c.append('        %s e = (%s)%s;' % (exp_c, exp_c, cint(exp)))
        m.append('        io.out("{}", a ** e);')
        # C reference: model MVS backend (64-bit multiply, truncate to result type)
        base_ext = "(uint64_t)(int64_t)" if base_signed else "(uint64_t)"
        res_rank = max(type_rank(base_mvs), type_rank(exp_mvs))
        res_mvs = base_mvs if type_rank(base_mvs) >= type_rank(exp_mvs) else exp_mvs
        res_bits = res_rank * 8
        res_ctype = {
            "i8": "int8_t", "u8": "uint8_t", "i16": "int16_t", "u16": "uint16_t",
            "i32": "int32_t", "u32": "uint32_t", "i64": "int64_t", "u64": "uint64_t",
        }[res_mvs]
        c.append('        {')
        c.append('            uint64_t base64 = %sa;' % base_ext)
        c.append('            int64_t orig = (int64_t)e, ex = orig < 0 ? -orig : orig;')
        c.append('            uint64_t r64 = 1;')
        c.append('            while (ex > 0) { r64 *= base64; ex--; }')
        if res_signed:
            c.append('            if (orig < 0) r64 = (uint64_t)((int64_t)1 / (int64_t)r64);')
        else:
            c.append('            if (orig < 0) r64 = (uint64_t)1 / r64;')
        c.append('            %s result = (%s)r64;' % (res_ctype, res_ctype))
        c.append('            printf("%s\\n", %s result);' % (fmt, cast))
        c.append('        }')
        n += 1
        m.append('    }')
        c.append('    }')
    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


def main():
    out = os.path.join('tests', 'diff')
    os.makedirs(out, exist_ok=True)
    total = 0

    for name, ctype, signed, bits in INT_TYPES:
        mvs, ref, n = gen_int(name, ctype, signed, bits)
        with open(os.path.join(out, 'pow_%s.mvs' % name), 'w', newline='\n') as f:
            f.write(mvs)
        with open(os.path.join(out, 'pow_%s.c' % name), 'w', newline='\n') as f:
            f.write(ref)
        total += n
        print('  wrote pow_%s  (%d checks)' % (name, n))

    mvs, ref, n = gen_float()
    with open(os.path.join(out, 'pow_f64.mvs'), 'w', newline='\n') as f:
        f.write(mvs)
    with open(os.path.join(out, 'pow_f64.c'), 'w', newline='\n') as f:
        f.write(ref)
    total += n
    print('  wrote pow_f64  (%d checks)' % n)

    for base_mvs, base_c, exp_mvs, exp_c, tag in CROSS_PAIRS:
        mvs, ref, n = gen_cross(base_mvs, base_c, exp_mvs, exp_c, tag)
        with open(os.path.join(out, 'pow_%s.mvs' % tag), 'w', newline='\n') as f:
            f.write(mvs)
        with open(os.path.join(out, 'pow_%s.c' % tag), 'w', newline='\n') as f:
            f.write(ref)
        total += n
        print('  wrote pow_%s  (%d checks)' % (tag, n))

    print('total: %d power-operator checks' % total)


if __name__ == '__main__':
    main()
