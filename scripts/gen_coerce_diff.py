#!/usr/bin/env python3
"""Generate the implicit-coercion axis: tests/diff/coerce_<type>.{mvs,c}

Every unsigned integer type (u8..u64, usize) implicitly coerced to f64 through
five paths: assignment, function argument, return value, binary op, compound
assignment. Uses boundary values that distinguish signed from unsigned
conversion (values >= 2^63 for 64-bit types). C is the oracle.

Run from the repo root: python3 scripts/gen_coerce_diff.py
"""
import os

UNSIGNED_TYPES = [
    # mvs_name, c_type, bits
    ("u8",    "uint8_t",   8),
    ("u16",   "uint16_t",  16),
    ("u32",   "uint32_t",  32),
    ("u64",   "uint64_t",  64),
    ("usize", "uintptr_t", 64),
]

SIGNED_TYPES = [
    ("i8",    "int8_t",   8),
    ("i16",   "int16_t",  16),
    ("i32",   "int32_t",  32),
    ("i64",   "int64_t",  64),
    ("isize", "intptr_t", 64),
]

def cint(v):
    if v > 0x7fffffffffffffff:
        return '%dULL' % v
    if v < -0x7fffffffffffffff:
        return '(-9223372036854775807LL - 1)'
    return '%dLL' % v

def test_values(signed, bits):
    if signed:
        hi = (1 << (bits - 1)) - 1
        lo = -(1 << (bits - 1))
        return [0, 1, -1, hi, lo]
    hi = (1 << bits) - 1
    vals = [0, 1, hi]
    mid = hi // 2 + 1
    if mid not in vals:
        vals.append(mid)
    return vals


def gen_coerce(src_name, src_ctype, src_signed, src_bits):
    """Generate coerce_<type>.mvs and .c testing implicit int<->float coercion."""
    vals = test_values(src_signed, src_bits)

    m = [
        '// GENERATED by scripts/gen_coerce_diff.py: implicit coercion from %s' % src_name,
        '// C is the oracle; difftest.sh requires byte-identical output.',
        'import { io } from "std";',
        '',
        'func take_f64(x: f64) -> f64 { return x; }',
        'func ret_f64(x: %s) -> f64 { return x; }' % src_name,
        '',
        'func main() -> i8 {',
    ]
    c = [
        '/* GENERATED by scripts/gen_coerce_diff.py: reference for coerce_%s.mvs */' % src_name,
        '#include <stdio.h>',
        '#include <stdint.h>',
        '',
        'double take_f64(double x) { return x; }',
        'double ret_f64(%s x) { return (double)x; }' % src_ctype,
        '',
        'int main(void) {',
    ]
    n = 0

    for v in vals:
        m.append('    {')
        c.append('    {')
        m.append('        let a: %s = %s;' % (src_name, str(v)))
        c.append('        %s a = (%s)%s;' % (src_ctype, src_ctype, cint(v)))

        # path 1: assignment
        m.append('        let f1: f64 = a; io.out("{}", f1);')
        c.append('        { double f1 = (double)a; printf("%f\\n", f1); }')
        n += 1

        # path 2: function argument
        m.append('        io.out("{}", take_f64(a));')
        c.append('        printf("%f\\n", take_f64((double)a));')
        n += 1

        # path 3: return coercion
        m.append('        io.out("{}", ret_f64(a));')
        c.append('        printf("%f\\n", ret_f64(a));')
        n += 1

        # path 4: binary op (int + float)
        m.append('        io.out("{}", a + 0.0);')
        c.append('        printf("%f\\n", (double)a + 0.0);')
        n += 1

        # path 5: compound assignment (float += int)
        m.append('        let acc: f64 = 0.0; acc += a; io.out("{}", acc);')
        c.append('        { double acc = 0.0; acc += (double)a; printf("%f\\n", acc); }')
        n += 1

        m.append('    }')
        c.append('    }')

    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


def main():
    out = os.path.join('tests', 'diff')
    os.makedirs(out, exist_ok=True)
    total = 0
    for src_name, src_ctype, src_bits in UNSIGNED_TYPES:
        mvs, ref, n = gen_coerce(src_name, src_ctype, False, src_bits)
        with open(os.path.join(out, 'coerce_%s.mvs' % src_name), 'w', newline='\n') as f:
            f.write(mvs)
        with open(os.path.join(out, 'coerce_%s.c' % src_name), 'w', newline='\n') as f:
            f.write(ref)
        total += n
        print('  wrote coerce_%s  (%d checks)' % (src_name, n))

    for src_name, src_ctype, src_bits in SIGNED_TYPES:
        mvs, ref, n = gen_coerce(src_name, src_ctype, True, src_bits)
        with open(os.path.join(out, 'coerce_%s.mvs' % src_name), 'w', newline='\n') as f:
            f.write(mvs)
        with open(os.path.join(out, 'coerce_%s.c' % src_name), 'w', newline='\n') as f:
            f.write(ref)
        total += n
        print('  wrote coerce_%s  (%d checks)' % (src_name, n))

    print('total: %d implicit-coercion checks' % total)


if __name__ == '__main__':
    main()
