#!/usr/bin/env python3
"""Generate the signed-shift axis: tests/diff/shift_<type>.{mvs,c}

The ops_diff axis deliberately skips shifts when a < 0 because C left-shift
of negative values is UB (before C23).  This axis fills that gap by modeling
MVS backend behavior in the C reference:

  - Operands are sign-extended to 64-bit
  - Left shift uses unsigned 64-bit arithmetic (no C UB)
  - Right shift uses signed 64-bit arithmetic (clang arithmetic shift)
  - Result is truncated to the target type, then sign-extended for printing

Run from the repo root: python3 scripts/gen_shift_diff.py
"""
import os

TYPES = [
    # (mvs_name, c_type, bits)
    ("i8",    "int8_t",    8),
    ("i16",   "int16_t",   16),
    ("i32",   "int32_t",   32),
    ("i64",   "int64_t",   64),
    ("isize", "intptr_t",  64),
]


def values(bits):
    """Negative values worth testing for shift operands."""
    lo = -(1 << (bits - 1))
    vs = [-1, lo, lo + 1, -7]
    if bits > 8:
        vs.append(-128)
    return vs


def shift_amounts(bits):
    """Shift counts to test (always within [1, bits-1])."""
    s = [1, 3]
    if bits >= 16:
        s.append(bits // 2)
    s.append(bits - 1)
    seen = set()
    return [x for x in s if x not in seen and not seen.add(x)]


def cint(v):
    if v > 0x7FFFFFFFFFFFFFFF:
        return '%dULL' % v
    if v < -0x7FFFFFFFFFFFFFFF:
        return '(-9223372036854775807LL - 1)'
    return '%dLL' % v


def gen(name, ctype, bits):
    fmt = "%lld"
    cast = "(long long)"
    m = [
        '// GENERATED by scripts/gen_shift_diff.py: shift ops on negative %s' % name,
        '// C file is the reference; difftest.sh requires identical output.',
        'use std::io;',
        '',
        'func main() -> i8 {',
    ]
    c = [
        '/* GENERATED by scripts/gen_shift_diff.py: reference for shift_%s.mvs */' % name,
        '#include <stdio.h>',
        '#include <stdint.h>',
        '',
        'int main(void) {',
    ]
    n = 0
    for a in values(bits):
        for sh in shift_amounts(bits):
            m.append('    {')
            c.append('    {')
            m.append('        let a: %s = %s;' % (name, a))
            c.append('        %s a = (%s)%s;' % (ctype, ctype, cint(a)))

            # Left shift: model with uint64_t to avoid C UB
            m.append('        let r_shl: %s = a << %d; io.out("{}", r_shl);' % (name, sh))
            c.append('        {')
            c.append('            uint64_t a64 = (uint64_t)(int64_t)a;')
            c.append('            uint64_t r64 = a64 << %d;' % sh)
            c.append('            %s result = (%s)r64;' % (ctype, ctype))
            c.append('            printf("%s\\n", %s result);' % (fmt, cast))
            c.append('        }')
            n += 1

            # Right shift (arithmetic): model with int64_t
            m.append('        let r_shr: %s = a >> %d; io.out("{}", r_shr);' % (name, sh))
            c.append('        {')
            c.append('            int64_t a64 = (int64_t)a;')
            c.append('            int64_t r64 = a64 >> %d;' % sh)
            c.append('            %s result = (%s)r64;' % (ctype, ctype))
            c.append('            printf("%s\\n", %s result);' % (fmt, cast))
            c.append('        }')
            n += 1

            m.append('    }')
            c.append('    }')
    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


def main():
    out = os.path.join('tests', 'diff')
    os.makedirs(out, exist_ok=True)
    total = 0
    for name, ctype, bits in TYPES:
        mvs, ref, n = gen(name, ctype, bits)
        with open(os.path.join(out, 'shift_%s.mvs' % name), 'w', newline='\n') as f:
            f.write(mvs)
        with open(os.path.join(out, 'shift_%s.c' % name), 'w', newline='\n') as f:
            f.write(ref)
        total += n
        print('  wrote shift_%s  (%d checks)' % (name, n))
    print('total: %d signed-shift checks' % total)


if __name__ == '__main__':
    main()
