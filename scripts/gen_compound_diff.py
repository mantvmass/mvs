#!/usr/bin/env python3
"""Generate the compound-assignment axis: tests/diff/compound_<type>.{mvs,c}

Every compound assignment operator (+=, -=, *=, /=) on every numeric type
(10 integer + 2 float = 12 types) with boundary values that stress
wraparound, truncation, and the load-modify-store codegen path. C is the
oracle; difftest.sh requires byte-identical output.

Run from the repo root: python3 scripts/gen_compound_diff.py
"""
import os

INT_TYPES = [
    # mvs_name, c_type, signed, bits
    ("i8",    "int8_t",   True,  8),
    ("i16",   "int16_t",  True,  16),
    ("i32",   "int32_t",  True,  32),
    ("i64",   "int64_t",  True,  64),
    ("isize", "intptr_t", True,  64),
    ("u8",    "uint8_t",  False, 8),
    ("u16",   "uint16_t", False, 16),
    ("u32",   "uint32_t", False, 32),
    ("u64",   "uint64_t", False, 64),
    ("usize", "uintptr_t", False, 64),
]

FLOAT_TYPES = [
    # mvs_name, c_type, suffix
    ("f32", "float",  "f"),
    ("f64", "double", ""),
]

OPS = [("add", "+="), ("sub", "-="), ("mul", "*=")]
DIV = [("div", "/=")]


def cint(v):
    if v > 0x7fffffffffffffff:
        return '%dULL' % v
    if v < -0x7fffffffffffffff:
        return '(-9223372036854775807LL - 1)'
    return '%dLL' % v


def int_pairs(signed, bits):
    """(a, b) pairs for compound assignment on integer types."""
    if signed:
        hi = (1 << (bits - 1)) - 1
        lo = -(1 << (bits - 1))
        return [
            (hi, 1),       # overflow wraps on +=
            (lo, 1),       # near min
            (0, 0),        # identity
            (hi, hi),      # large * large wraps on *=
            (-1, -1),      # neg * neg
            (7, 3),        # typical
            (-7, 3),       # mixed sign
            (lo, -1),      # min * -1 wraps on *=
        ]
    hi = (1 << bits) - 1
    return [
        (hi, 1),           # overflow wraps on +=
        (0, 0),            # identity
        (hi, hi),          # large * large wraps
        (1, 1),            # small
        (7, 3),            # typical
        (hi // 2 + 1, 3),  # mid-range
    ]


def float_pairs():
    return [
        (1.0, 2.0),
        (0.0, 1.0),
        (-1.0, 3.0),
        (1.5, 0.5),
        (1e15, 1.0),
        (-1e15, 1e15),
        (0.1, 0.2),
        (-0.5, -0.25),
    ]


def gen_int(name, ctype, signed, bits):
    fmt = "%lld" if signed else "%llu"
    cast = "(long long)" if signed else "(unsigned long long)"
    m = [
        '// GENERATED by scripts/gen_compound_diff.py: compound assignment on %s' % name,
        '// C is the oracle; difftest.sh requires byte-identical output.',
        'import { io } from "std";',
        '',
        'func main() -> i8 {',
    ]
    c = [
        '/* GENERATED by scripts/gen_compound_diff.py: reference for compound_%s.mvs */' % name,
        '#include <stdio.h>',
        '#include <stdint.h>',
        '',
        'int main(void) {',
    ]
    n = 0
    lo = -(1 << (bits - 1)) if signed else 0

    for (a, b) in int_pairs(signed, bits):
        m.append('    {')
        c.append('    {')
        m.append('        let v: %s = %s;' % (name, str(a)))
        c.append('        %s v = (%s)%s;' % (ctype, ctype, cint(a)))

        for label, op in OPS:
            m.append('        { let a: %s = v; a %s %s; io.out("{}", a); }'
                     % (name, op, str(b)))
            c.append('        { %s a = v; a %s (%s)%s; printf("%s\\n", %s a); }'
                     % (ctype, op, ctype, cint(b), fmt, cast))
            n += 1

        for label, op in DIV:
            if b == 0:
                continue
            if signed and a == lo and b == -1:
                continue
            m.append('        { let a: %s = v; a %s %s; io.out("{}", a); }'
                     % (name, op, str(b)))
            c.append('        { %s a = v; a %s (%s)%s; printf("%s\\n", %s a); }'
                     % (ctype, op, ctype, cint(b), fmt, cast))
            n += 1

        m.append('    }')
        c.append('    }')

    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


def gen_float(name, ctype, suffix):
    m = [
        '// GENERATED by scripts/gen_compound_diff.py: compound assignment on %s' % name,
        '// C is the oracle; difftest.sh requires byte-identical output.',
        'import { io } from "std";',
        '',
        'func main() -> i8 {',
    ]
    c = [
        '/* GENERATED by scripts/gen_compound_diff.py: reference for compound_%s.mvs */' % name,
        '#include <stdio.h>',
        '',
        'int main(void) {',
    ]
    n = 0
    for (a, b) in float_pairs():
        m.append('    {')
        c.append('    {')
        m.append('        let v: %s = %r;' % (name, a))
        c.append('        %s v = %r%s;' % (ctype, a, suffix))

        for label, op in OPS + DIV:
            if op == '/=' and b == 0.0:
                continue
            m.append('        { let a: %s = v; a %s %r; io.out("{}", a); }'
                     % (name, op, b))
            # no suffix on RHS: MVS literals are f64, so C must also use
            # double on the RHS to get the same promotion semantics
            c.append('        { %s a = v; a %s %r; printf("%%f\\n", (double)a); }'
                     % (ctype, op, b))
            n += 1

        m.append('    }')
        c.append('    }')

    m += ['    return 0;', '}', '']
    c += ['    return 0;', '}', '']
    return '\n'.join(m), '\n'.join(c), n


def main():
    out = os.path.join('tests', 'diff')
    os.makedirs(out, exist_ok=True)
    total = 0

    for name, ctype, signed, bits in INT_TYPES:
        mvs, ref, n = gen_int(name, ctype, signed, bits)
        with open(os.path.join(out, 'compound_%s.mvs' % name), 'w', newline='\n') as f:
            f.write(mvs)
        with open(os.path.join(out, 'compound_%s.c' % name), 'w', newline='\n') as f:
            f.write(ref)
        total += n
        print('  wrote compound_%s  (%d checks)' % (name, n))

    for name, ctype, suffix in FLOAT_TYPES:
        mvs, ref, n = gen_float(name, ctype, suffix)
        with open(os.path.join(out, 'compound_%s.mvs' % name), 'w', newline='\n') as f:
            f.write(mvs)
        with open(os.path.join(out, 'compound_%s.c' % name), 'w', newline='\n') as f:
            f.write(ref)
        total += n
        print('  wrote compound_%s  (%d checks)' % (name, n))

    print('total: %d compound-assignment checks' % total)


if __name__ == '__main__':
    main()
